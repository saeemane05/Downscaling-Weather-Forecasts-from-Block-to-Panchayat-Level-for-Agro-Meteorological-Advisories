"""
SIH26 - UNIVERSAL GP BOUNDARY INGESTION ENGINE

Purpose
-------
Collect official Gram Manchitra Gram Panchayat boundaries and build a
downstream-safe GP master without hardcoding state/block-specific fixes.

Design principles
-----------------
1. Raw official GP and Block snapshots are preserved untouched.
2. GP IDs/names are detected dynamically.
3. Repeated GP IDs are NOT blindly dropped.
4. Every source geometry is spatially assessed against the complete
   official Block layer returned by Gram Manchitra.
5. The engine dynamically distinguishes:
      - EXACT_DUPLICATE
      - VALID_MULTIPART
      - CROSS_BLOCK_SOURCE
      - PARTIAL_BLOCK_INTERSECTION
      - NAME_CONFLICT
      - GEOMETRY_INVALID
      - UNRESOLVED
6. No "largest polygon" rule is used.
7. No synthetic geometry is invented.
8. For modelling inside the requested Block, an analysis geometry is
   generated by intersection with the requested Block. The original
   official geometry is preserved separately in source_geometry_wkt.
9. A GP with source geometry extending outside the requested Block is
   not silently discarded; it is retained and flagged.
10. Centroids and areas are calculated in a projected CRS.

The resulting gp_master contains one logical row per GP ID returned by the
official GP query. Source-level provenance and spatial membership are
stored in duplicate_gp_source_audit.csv.
"""

