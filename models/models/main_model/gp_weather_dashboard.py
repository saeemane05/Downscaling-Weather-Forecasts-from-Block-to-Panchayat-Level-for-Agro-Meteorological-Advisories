def safe_label(x):
    return str(x).replace("_", " ").title()


def discover_blocks():
    """Return completed Stage-2 blocks that contain a current forecast."""
    blocks = []
    if not STAGE2_ROOT.exists():
        return blocks

    for forecast_file in STAGE2_ROOT.glob("*/*/*/stage2_current_gp_forecast.csv"):
        rel = forecast_file.relative_to(STAGE2_ROOT)
        if len(rel.parts) != 4:
            continue
        state, district, block, _ = rel.parts
        blocks.append(
            {
                "state": state,
                "district": district,
                "block": block,
                "forecast_file": forecast_file,
            }
        )

    return sorted(blocks, key=lambda x: (x["state"], x["district"], x["block"]))


def normalize_columns(df):
    df = df.copy()
    df.columns = [str(c).strip() for c in df.columns]
    return df


def find_coordinate_columns(df):
    """Find GP latitude/longitude columns from the existing GP feature table."""
    cols = list(df.columns)

    lat_candidates = [
        "landcover__centroid_lat",
        "centroid_lat",
        "latitude",
        "lat",
        "gp_lat",
        "gp_latitude",
    ]
    lon_candidates = [
        "landcover__centroid_lon",
        "centroid_lon",
        "longitude",
        "lon",
        "lng",
        "gp_lon",
        "gp_longitude",
    ]

    lat = next((c for c in lat_candidates if c in cols), None)
    lon = next((c for c in lon_candidates if c in cols), None)

    if lat and lon:
        return lat, lon

    # Fallback: fuzzy search
    lat = next((c for c in cols if "lat" in c.lower() and "lon" not in c.lower()), None)
    lon = next((c for c in cols if "lon" in c.lower() or "lng" in c.lower()), None)
    return lat, lon


def find_gp_feature_file(state, district, block):
    """
    Locate the merged/static GP feature table for the selected block.

    We deliberately inspect column names instead of assuming one exact filename,
    because the upstream GP collector may change its filename while preserving
    the GP feature contract.
    """
    search_roots = [
        GP_ROOT / state / district / block,
        PROJECT_ROOT / "datasets" / "cleaned" / state / district / block,
        PROJECT_ROOT / "datasets" / "engineered" / state / district / block,
    ]

    candidates = []
    for root in search_roots:
        if not root.exists():
            continue
        candidates.extend(root.rglob("*.csv"))

    # Also search the whole GP tree as a fallback.
    if not candidates and GP_ROOT.exists():
        candidates = list(GP_ROOT.rglob("*.csv"))

    best = None
    best_score = -1

    for f in candidates:
        try:
            # Avoid reading enormous unrelated files where possible.
            sample = pd.read_csv(f, nrows=3)
            sample = normalize_columns(sample)
            lat, lon = find_coordinate_columns(sample)
            has_gp = "gp_id" in sample.columns or any(
                c.lower() in {"gpcode", "gp_code", "panchayat_code"} for c in sample.columns
            )

            if not (lat and lon and has_gp):
                continue

            score = 10
            name = f.name.lower()
            if "merge" in name:
                score += 5
            if "gp" in name:
                score += 2
            if "feature" in name:
                score += 2

            if score > best_score:
                best = f
                best_score = score
        except Exception:
            continue

    return best


def find_boundary_file(state, district, block):
    """
    Locate the OFFICIAL requested block boundary.

    Important:
    - The project contains both Block GeoJSON and GP GeoJSON files.
    - The previous implementation could accidentally select a GP file,
      producing a few disconnected polygons instead of the complete block.
    - We therefore validate the GeoJSON properties and require the selected
      feature to match the requested state/district/block.
    """
    roots = [
        GP_ROOT / state / district / block,
        PROJECT_ROOT / "datasets" / "cleaned" / state / district / block,
    ]

    candidates = []
    for root in roots:
        if root.exists():
            candidates.extend(root.rglob("*.geojson"))
            candidates.extend(root.rglob("*.json"))

    def norm(v):
        return str(v or "").strip().upper().replace("_", " ").replace("-", " ")

    valid_block_candidates = []

    for f in candidates:
        try:
            with open(f, "r", encoding="utf-8") as fh:
                obj = json.load(fh)

            if obj.get("type") != "FeatureCollection":
                continue

            features = obj.get("features", [])
            if not features:
                continue

            # Look for a feature whose administrative identity matches
            # the selected block.
            matched = False
            polygon_count = 0

            for feature in features:
                props = feature.get("properties", {}) or {}
                geom = feature.get("geometry") or {}
                gtype = geom.get("type", "")

                if gtype in {"Polygon", "MultiPolygon"}:
                    polygon_count += 1

                state_val = props.get("state", props.get("stname", ""))
                district_val = props.get("district", props.get("dtname", ""))
                block_val = props.get(
                    "block_name",
                    props.get("blkname", props.get("block", ""))
                )

                if (
                    norm(state_val) == norm(state)
                    and norm(district_val) == norm(district)
                    and norm(block_val) == norm(block)
                ):
                    matched = True

            if not matched:
                continue

            name = f.name.lower()

            # Strong preference for the official Block snapshot produced by
            # 01_gp_boundary.py. Never prefer a GP snapshot merely because
            # its filename contains "boundary".
            score = 100

            if "all_blocks" in name:
                score += 100
            if "block" in name:
                score += 50
            if "gram_manchitra" in name:
                score += 20
            if "gp" in name:
                score -= 100
            if "panchayat" in name:
                score -= 50

            # A one-feature polygon matching the requested block is ideal.
            if len(features) == 1 and polygon_count == 1:
                score += 30

            valid_block_candidates.append((score, f))

        except Exception:
            continue

    if not valid_block_candidates:
        return None

    valid_block_candidates.sort(
        key=lambda x: (-x[0], str(x[1]))
    )

    return valid_block_candidates[0][1]


def find_gp_boundary_file(state, district, block):
    """
    Locate the processed official GP master geometry for the selected block.

    Priority:
      1. gp_master.geojson produced by 01_gp_boundary.py
      2. raw Gram Manchitra GP GeoJSON snapshots

    The GP layer is drawn as an overlay; weather markers remain on top.
    """
    roots = [
        GP_ROOT / state / district / block,
        PROJECT_ROOT / "datasets" / "cleaned" / state / district / block,
    ]

    candidates = []
    for root in roots:
        if root.exists():
            candidates.extend(root.rglob("*.geojson"))

    # Strong preference for the processed logical GP master.
    preferred = [
        f for f in candidates
        if f.name.lower() == "gp_master.geojson"
    ]
    if preferred:
        return preferred[0]

    # Fallback to official Gram Manchitra GP snapshots.
    preferred = [
        f for f in candidates
        if "gram_manchitra_gp" in f.name.lower()
    ]
    if preferred:
        preferred.sort(key=lambda x: x.stat().st_mtime, reverse=True)
        return preferred[0]

    return None


def load_forecast(forecast_file):
    df = pd.read_csv(forecast_file)
    df = normalize_columns(df)

    required = [
        "gp_id",
        "target_date",
        "forecast_horizon_day",
        "gp_temperature_corrected",
        "gp_humidity_corrected",
        "gp_precipitation_corrected",
        "gp_wind_corrected",
    ]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Forecast file is missing columns: {missing}")

    df["gp_id"] = df["gp_id"].astype(str)
    df["target_date"] = pd.to_datetime(df["target_date"], errors="coerce")
    df["forecast_horizon_day"] = pd.to_numeric(
        df["forecast_horizon_day"], errors="coerce"
    ).astype("Int64")

    return df


def load_gp_features(feature_file):
    gp = pd.read_csv(feature_file)
    gp = normalize_columns(gp)

    if "gp_id" not in gp.columns:
        # Common alternatives
        alt = next(
            (c for c in gp.columns if c.lower() in {"gpcode", "gp_code", "panchayat_code"}),
            None,
        )
        if alt:
            gp["gp_id"] = gp[alt].astype(str)
        else:
            raise ValueError("GP feature file has no gp_id column.")

    lat_col, lon_col = find_coordinate_columns(gp)
    if not lat_col or not lon_col:
        raise ValueError(
            "Could not find GP latitude/longitude columns in the GP feature table."
        )

    gp["gp_id"] = gp["gp_id"].astype(str)
    gp["latitude"] = pd.to_numeric(gp[lat_col], errors="coerce")
    gp["longitude"] = pd.to_numeric(gp[lon_col], errors="coerce")

    gp = gp.dropna(subset=["latitude", "longitude"])
    gp = gp.drop_duplicates("gp_id")

    # Keep a useful GP display name if available.
    name_candidates = [
        "gp_name",
        "GP_NAME",
        "gpname",
        "gram_panchayat_name",
        "panchayat_name",
        "name",
    ]
    name_col = next((c for c in name_candidates if c in gp.columns), None)
    if name_col:
        gp["display_name"] = gp[name_col].astype(str)
    else:
        gp["display_name"] = "GP " + gp["gp_id"]

    return gp


