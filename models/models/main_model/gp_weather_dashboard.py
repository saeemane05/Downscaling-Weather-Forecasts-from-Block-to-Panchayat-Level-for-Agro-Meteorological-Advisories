def merge_forecast_and_gps(forecast, gps):
    out = forecast.merge(
        gps[["gp_id", "display_name", "latitude", "longitude"]],
        on="gp_id",
        how="left",
        validate="many_to_one",
    )
    return out.dropna(subset=["latitude", "longitude"])


def color_for_value(value, vmin, vmax, variable):
    """Simple dynamic color scale without requiring geopandas."""
    if not np.isfinite(value):
        return "#808080"

    if vmax <= vmin:
        t = 0.5
    else:
        t = float((value - vmin) / (vmax - vmin))
        t = max(0.0, min(1.0, t))

    # Compact palettes designed for map markers.
    if variable == "Temperature":
        stops = [
            (0.0, "#2b83ba"),
            (0.25, "#abdda4"),
            (0.5, "#ffffbf"),
            (0.75, "#fdae61"),
            (1.0, "#d7191c"),
        ]
    elif variable == "Humidity":
        stops = [
            (0.0, "#eff3ff"),
            (0.35, "#9ecae1"),
            (0.7, "#3182bd"),
            (1.0, "#08519c"),
        ]
    elif variable == "Precipitation":
        stops = [
            (0.0, "#ffffcc"),
            (0.35, "#a1dab4"),
            (0.7, "#41b6c4"),
            (1.0, "#225ea8"),
        ]
    else:
        stops = [
            (0.0, "#f7fcfd"),
            (0.35, "#9ecae1"),
            (0.7, "#2c7fb8"),
            (1.0, "#253494"),
        ]

    for i in range(len(stops) - 1):
        a, ca = stops[i]
        b, cb = stops[i + 1]
        if t <= b:
            u = (t - a) / max(b - a, 1e-9)
            import matplotlib.colors as mcolors
            c1 = np.array(mcolors.to_rgb(ca))
            c2 = np.array(mcolors.to_rgb(cb))
            rgb = c1 * (1 - u) + c2 * u
            return mcolors.to_hex(rgb)

    return stops[-1][1]


@st.cache_data(show_spinner=False)
def load_simplified_geojson(boundary_file, allowed_gp_ids=None, tolerance=0.00015):
    """
    Load GeoJSON, optionally filter GP features, simplify geometry,
    and retain only the properties required by the dashboard.

    This prevents large GeoJSON payloads from being sent to the browser.
    """
    with open(boundary_file, "r", encoding="utf-8") as f:
        geo = json.load(f)

    allowed = None
    if allowed_gp_ids is not None:
        allowed = {str(x).strip() for x in allowed_gp_ids}

    compact_features = []

    for feature in geo.get("features", []):
        props = feature.get("properties", {}) or {}
        geom = feature.get("geometry")

        if not geom:
            continue

        # Identify GP ID from common property names.
        gp_id = None
        for key in [
            "gp_id",
            "GP_ID",
            "gpcode",
            "gp_code",
            "GP_CODE",
            "panchayat_code",
            "PANCHAYAT_CODE",
            "lgd_code",
            "LGD_CODE",
            "id",
            "ID",
        ]:
            if key in props and props[key] not in (None, ""):
                gp_id = str(props[key]).strip()
                break

        # When requested, retain only GPs belonging to the selected block.
        if allowed is not None:
            if gp_id is None or gp_id not in allowed:
                continue

        # Identify a compact display name.
        gp_name = None
        for key in [
            "gp_name",
            "GP_NAME",
            "gpname",
            "gram_panchayat_name",
            "GRAM_PANCHAYAT_NAME",
            "panchayat_name",
            "PANCHAYAT_NAME",
            "name",
            "NAME",
        ]:
            if key in props and props[key] not in (None, ""):
                gp_name = str(props[key])
                break

        if gp_name is None:
            gp_name = f"GP {gp_id}" if gp_id else "Gram Panchayat"

        # Simplify geometry while preserving topology.
        try:
            geom_obj = shape(geom)

            if not geom_obj.is_empty:
                geom_obj = geom_obj.simplify(
                    tolerance,
                    preserve_topology=True,
                )

            simplified_geometry = mapping(geom_obj)
        except Exception:
            simplified_geometry = geom

        compact_features.append(
            {
                "type": "Feature",
                "properties": {
                    "gp_id": gp_id or "",
                    "gp_name": gp_name,
                },
                "geometry": simplified_geometry,
            }
        )

    return {
        "type": "FeatureCollection",
        "features": compact_features,
    }


def add_boundary(m, boundary_file):
    """Add a simplified block boundary to the map."""
    if not boundary_file:
        return

    try:
        geo = load_simplified_geojson(
            str(boundary_file),
            allowed_gp_ids=None,
            tolerance=0.00015,
        )

        if not geo.get("features"):
            return

        folium.GeoJson(
            geo,
            name="Block Boundary",
            style_function=lambda _: {
                "fillColor": "#0d0101",
                "color": "#ffffff",
                "weight": 4,
                "fillOpacity": 0.03,
            },
        ).add_to(m)

    except Exception as exc:
        st.sidebar.warning(
            f"Block boundary could not be loaded: {exc}"
        )


def add_gp_boundaries(m, gp_boundary_file, gp_ids):
    """
    Add only the GP polygons needed for the currently selected block.

    This avoids sending the entire gp_master.geojson to the browser.
    """
    if not gp_boundary_file:
        return

    try:
        compact_geo = load_simplified_geojson(
            str(gp_boundary_file),
            allowed_gp_ids=tuple(sorted(str(x) for x in gp_ids)),
            tolerance=0.00015,
        )

        if not compact_geo.get("features"):
            st.sidebar.warning(
                "GP boundary file was found, but no matching GP IDs were found."
            )
            return

        folium.GeoJson(
            compact_geo,
            name="Gram Panchayat Boundaries",
            style_function=lambda _: {
                "fillColor": "#ffffff",
                "color": "#ffffff",
                "weight": 1.1,
                "opacity": 0.85,
                "fillOpacity": 0.0,
            },
            highlight_function=lambda _: {
                "color": "#00ffff",
                "weight": 2.5,
                "opacity": 1.0,
                "fillOpacity": 0.05,
            },
            tooltip=folium.GeoJsonTooltip(
                fields=["gp_name", "gp_id"],
                aliases=["Gram Panchayat", "GP ID"],
                localize=True,
                sticky=False,
                labels=True,
            ),
        ).add_to(m)

    except Exception as exc:
        st.sidebar.warning(
            f"GP boundary overlay could not be loaded: {exc}"
        )


def build_map(day_df, variable, selected_gp_id=None, boundary_file=None, gp_boundary_file=None):
    center_lat = day_df["latitude"].mean()
    center_lon = day_df["longitude"].mean()

    m = folium.Map(
        location=[center_lat, center_lon],
        zoom_start=10,
        control_scale=True,
        tiles=None,
    )

    # Satellite base similar to the requested visual.
    folium.TileLayer(
        tiles=(
            "https://server.arcgisonline.com/ArcGIS/rest/services/"
            "World_Imagery/MapServer/tile/{z}/{y}/{x}"
        ),
        attr="Esri World Imagery",
        name="Satellite",
        overlay=False,
        control=True,
    ).add_to(m)

    folium.TileLayer(
        "OpenStreetMap",
        name="Street Map",
        overlay=False,
        control=True,
    ).add_to(m)

    add_boundary(m, boundary_file)

    # -------------------------------------------------------------
    # Gram Panchayat boundary overlay
    # -------------------------------------------------------------
    add_gp_boundaries(
        m,
        gp_boundary_file,
        day_df["gp_id"].unique(),
    )


    cfg = VARIABLES[variable]
    val_col = cfg["forecast"]

    vals = pd.to_numeric(day_df[val_col], errors="coerce")
    vmin = float(vals.min())
    vmax = float(vals.max())

    for _, row in day_df.iterrows():
        value = float(row[val_col])
        color = color_for_value(value, vmin, vmax, variable)

        selected = str(row["gp_id"]) == str(selected_gp_id)

        popup_html = f"""
        <div style="font-family:Arial;min-width:250px">
          <h4 style="margin-bottom:6px">{row['display_name']}</h4>
          <b>GP ID:</b> {row['gp_id']}<br>
          <b>Coordinates:</b> {row['latitude']:.5f}, {row['longitude']:.5f}<br>
          <hr style="margin:7px 0">
          <b>D{int(row['forecast_horizon_day'])} — {row['target_date'].date()}</b><br>
          🌡️ Temperature: {row['gp_temperature_corrected']:.2f} °C<br>
          💧 Humidity: {row['gp_humidity_corrected']:.2f} %<br>
          🌧️ Precipitation: {row['gp_precipitation_corrected']:.2f} mm<br>
          💨 Wind: {row['gp_wind_corrected']:.2f} m/s
        </div>
        """

        folium.CircleMarker(
            location=[row["latitude"], row["longitude"]],
            radius=9 if selected else 7,
            color="#111827" if selected else "#ffffff",
            weight=3 if selected else 1,
            fill=True,
            fill_color=color,
            fill_opacity=0.92,
            popup=folium.Popup(popup_html, max_width=330),
            tooltip=f"{row['display_name']} — {value:.2f} {cfg['unit']}",
        ).add_to(m)

    Fullscreen(position="topright").add_to(m)
    folium.LayerControl(collapsed=False).add_to(m)

    return m


